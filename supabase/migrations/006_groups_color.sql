-- ============================================
-- 006: 모임 커버 색상 추가
-- 이미 schema.sql을 실행한 기존 프로젝트에 적용하는 추가 마이그레이션.
-- 사용법: Supabase 프로젝트 → SQL Editor → 통째로 붙여넣고 Run
-- ============================================

-- 카드 커버에 쓰는 색. hex가 아니라 "색 이름"(팔레트 토큰)을 저장한다.
-- 실제 색상값은 프론트엔드 CSS가 결정 → 다크모드에서 같은 이름에 다른 밝기를 줄 수 있다.
--
-- default 'gray'는 평상시 쓰이는 값이 아니라 안전망이다.
-- 색은 앱이 생성 시점에 팔레트에서 정해 넣고, 'gray'는 "아무도 색을 정하지 않음"을 뜻한다.
-- 그래서 gray는 사용자가 고를 수 있는 팔레트에는 넣지 않는다.
alter table groups
  add column color text not null default 'gray';

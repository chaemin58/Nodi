-- ============================================
-- 009: 모임 한 줄 메시지 (status_message)
--
-- 디스코드 채널 주제처럼, 모임 멤버 누구나 고칠 수 있는 공용 한 줄.
-- "우리 언제 만나?" "투표 빨리해라" 같은 걸 아무나 적고 지운다.
-- 누가 적었는지는 기록하지 않는다 — 작성자 개념이 없는 게 이 기능의 의도다.
--
-- 수정 권한은 008에서 이미 열렸다 (groups_update = is_group_member).
--
-- 사용법: Supabase 프로젝트 → SQL Editor → 통째로 붙여넣고 Run
-- ============================================

-- null 허용 = "아직 아무도 안 적음". 기본값을 빈 문자열로 두면
-- "안 적음"과 "적었다가 지움"이 구분되지 않으므로 null 로 둔다.
--
-- 길이 제한: 누구나 수정할 수 있는 칸이라 한 줄 분량으로 묶어둔다.
alter table groups
  add column status_message text check (char_length(status_message) <= 100);
